/* ==========================================================================
   Lumen — static catalogue API (GitHub Pages build)
   The GitHub Pages demo has no Express server, so this module implements the
   same handful of read-only endpoints the storefront uses, against the JSON
   snapshot generated by scripts/build-static-data.js.

   Response envelopes, query handling and sorting all mirror server.js so the
   React components do not need a single change.
   ========================================================================== */
const BASE = import.meta.env.BASE_URL || '/';
const DATA_URL = `${BASE}data/catalog.json`;

const SORTERS = {
  featured: (a, b) =>
    Number(b.isFeatured) - Number(a.isFeatured) ||
    new Date(b.createdAt) - new Date(a.createdAt) ||
    b.id - a.id,
  newest: (a, b) => new Date(b.createdAt) - new Date(a.createdAt) || b.id - a.id,
  oldest: (a, b) => new Date(a.createdAt) - new Date(b.createdAt) || a.id - b.id,
  'price-asc': (a, b) => currentPrice(a) - currentPrice(b) || a.id - b.id,
  'price-desc': (a, b) => currentPrice(b) - currentPrice(a) || b.id - a.id,
  'name-asc': (a, b) =>
    a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }) || a.id - b.id,
  'name-desc': (a, b) =>
    b.name.localeCompare(a.name, 'en', { sensitivity: 'base' }) || b.id - a.id,
  rating: (a, b) => b.rating - a.rating || b.reviewCount - a.reviewCount || a.id - b.id
};

let catalogPromise = null;

function currentPrice(product) {
  return product.salePrice !== null && product.salePrice !== undefined
    ? product.salePrice
    : product.price;
}

function resolveAsset(value) {
  if (!value) return null;
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(value)) return value;
  return `${BASE}${String(value).replace(/^\/+/, '')}`;
}

function decorate(product) {
  return {
    ...product,
    imageUrl: resolveAsset(product.imageUrl),
    additionalImages: (product.additionalImages || []).map(resolveAsset).filter(Boolean)
  };
}

function abortError() {
  const error = new Error('Request cancelled.');
  error.name = 'AbortError';
  return error;
}

function guard(promise, signal) {
  if (!signal) return promise;
  if (signal.aborted) return Promise.reject(abortError());

  return new Promise((resolve, reject) => {
    const onAbort = () => reject(abortError());
    signal.addEventListener('abort', onAbort, { once: true });
    promise.then(
      (value) => {
        signal.removeEventListener('abort', onAbort);
        resolve(value);
      },
      (error) => {
        signal.removeEventListener('abort', onAbort);
        reject(error);
      }
    );
  });
}

function loadCatalog() {
  if (!catalogPromise) {
    catalogPromise = fetch(DATA_URL, { headers: { Accept: 'application/json' } })
      .then(async (response) => {
        if (!response.ok) {
          throw new Error(
            `The static catalogue could not load (HTTP ${response.status}).`
          );
        }
        return response.json();
      })
      .catch((error) => {
        catalogPromise = null;
        throw error;
      });
  }
  return catalogPromise;
}

async function ready(signal) {
  return guard(loadCatalog(), signal);
}

function toInteger(value) {
  const number = Number(value);
  return Number.isFinite(number) ? Math.trunc(number) : null;
}

function matchesSearch(product, needle) {
  const haystack = `${product.name} ${product.brand} ${product.category}`.toLowerCase();
  return haystack.includes(needle.toLowerCase());
}

function toBoolean(value) {
  if (value === true || value === 'true' || value === 1 || value === '1') return true;
  if (value === false || value === 'false' || value === 0 || value === '0') return false;
  return null;
}

function relatedFor(products, product) {
  const pool = products.filter((item) => item.isActive !== false && item.id !== product.id);
  const sameCategory = pool
    .filter((item) => item.category === product.category)
    .sort(SORTERS.featured)
    .slice(0, 4);

  if (sameCategory.length >= 4) return sameCategory;

  const taken = new Set(sameCategory.map((item) => item.id));
  const fillers = pool
    .filter((item) => !taken.has(item.id))
    .sort(SORTERS.featured)
    .slice(0, 4 - sameCategory.length);

  return [...sameCategory, ...fillers];
}

function notFound(message) {
  const error = new Error(message);
  error.status = 404;
  error.code = 'NOT_FOUND';
  return error;
}

export function createStaticApi() {
  return {
    async listProducts(params = {}, options = {}) {
      const catalog = await ready(options.signal);

      const page = Math.max(1, toInteger(params.page) || 1);
      const limit = Math.min(100, Math.max(1, toInteger(params.limit) || 12));
      const sort = SORTERS[params.sort] ? params.sort : 'featured';
      const search = String(params.search || '').trim();
      const category = String(params.category || '').trim();
      const brand = String(params.brand || '').trim();
      const featured = toBoolean(params.featured);

      let rows = catalog.products.filter((product) => product.isActive !== false);

      if (search) rows = rows.filter((product) => matchesSearch(product, search));
      if (category) {
        rows = rows.filter(
          (product) => product.category.toLowerCase() === category.toLowerCase()
        );
      }
      if (brand) {
        rows = rows.filter(
          (product) => product.brand.toLowerCase() === brand.toLowerCase()
        );
      }
      if (featured !== null) {
        rows = rows.filter((product) => Boolean(product.isFeatured) === featured);
      }
      if (params.min_price !== undefined && params.min_price !== '') {
        const min = Number(params.min_price);
        if (Number.isFinite(min)) {
          rows = rows.filter((product) => currentPrice(product) >= min);
        }
      }
      if (params.max_price !== undefined && params.max_price !== '') {
        const max = Number(params.max_price);
        if (Number.isFinite(max)) {
          rows = rows.filter((product) => currentPrice(product) <= max);
        }
      }

      const sorted = [...rows].sort(SORTERS[sort]);
      const total = sorted.length;
      const totalPages = total === 0 ? 0 : Math.ceil(total / limit);
      const start = (page - 1) * limit;
      const pageRows = sorted.slice(start, start + limit);

      return {
        success: true,
        data: pageRows.map(decorate),
        meta: {
          page,
          limit,
          total,
          totalPages,
          count: pageRows.length,
          hasNextPage: page < totalPages,
          hasPrevPage: page > 1,
          sort,
          filters: {
            search: search || null,
            category: category || null,
            brand: brand || null,
            featured,
            includeInactive: false
          }
        }
      };
    },

    async getProduct(idOrSlug, options = {}) {
      const catalog = await ready(options.signal);
      const key = String(idOrSlug ?? '');
      const asNumber = toInteger(key);
      const product = catalog.products.find(
        (item) =>
          item.isActive !== false &&
          (item.slug === key || (asNumber !== null && item.id === asNumber))
      );

      if (!product) throw notFound('Product not found.');

      return {
        success: true,
        data: {
          ...decorate(product),
          related: relatedFor(catalog.products, product).map(decorate)
        }
      };
    },

    async getFeatured(limit = 8, options = {}) {
      const catalog = await ready(options.signal);
      const count = Math.min(50, Math.max(1, toInteger(limit) || 8));
      const rows = catalog.products
        .filter((product) => product.isActive !== false && product.isFeatured)
        .sort(SORTERS.newest)
        .slice(0, count);

      return { success: true, data: rows.map(decorate), meta: { total: rows.length, limit: count } };
    },

    async getCategories(options = {}) {
      const catalog = await ready(options.signal);
      const data = catalog.categories.map((category) => ({
        ...category,
        imageUrl: resolveAsset(category.imageUrl)
      }));
      return { success: true, data, meta: { total: data.length } };
    },

    async getBrands(options = {}) {
      const catalog = await ready(options.signal);
      return { success: true, data: catalog.brands, meta: { total: catalog.brands.length } };
    },

    async health(options = {}) {
      const catalog = await ready(options.signal);
      return {
        success: true,
        data: {
          status: 'ok',
          mode: 'static',
          products: catalog.products.length,
          generatedAt: catalog.generatedAt
        }
      };
    }
  };
}

export function clearStaticCache() {
  catalogPromise = null;
}
